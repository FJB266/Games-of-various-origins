function ikdFloodFill(col,row,target,repl){
  if(target===repl) return;
  const stack=[[col,row]];
  while(stack.length){
    const[c,r]=stack.pop();
    if(c<0||c>=IKD_COLS||r<0||r>=IKD_ROWS||ikdPixels[r][c]!==target) continue;
    ikdPixels[r][c]=repl; stack.push([c+1,r],[c-1,r],[c,r+1],[c,r-1]);
  }
}
