function loop(ts){
  requestAnimationFrame(loop);
  if(!lastTime) lastTime=ts;
  const dt=Math.min((ts-lastTime)/(1000/60),2);
  lastTime=ts;
  if(gameState==='playing')      { update(dt); gameDraw(); }
  else if(gameState==='dead')    { gameDraw(); }
}

